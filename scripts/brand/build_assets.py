# ---------------------------------------------------------------- OG image + WhatsApp cover
def card(cw, ch, wm_w, wm_top, sub_size, sub_base):
    sc = wm_w / W
    x = (cw - wm_w) / 2
    sub, sub_w = text_path("Software studio, Beirut", sub_size, wght=450, tracking=0.4)
    sx = (cw - sub_w) / 2
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{cw}" height="{ch}" viewBox="0 0 {cw} {ch}">\n'
        f'  <rect width="{cw}" height="{ch}" fill="{DARK_BG}"/>\n'
        f'  <g transform="translate({num(x)} {num(wm_top)}) scale({sc:.4f})">\n'
        f'    <path d="{wm["letters"]}" fill="{DARK_FG}"/>\n'
        f'    <path d="{wm["drops"]}" fill="{DARK_ACC}"/>\n'
        f"  </g>\n"
        f'  <g transform="translate({num(sx)} {num(sub_base)})" aria-label="Software studio, Beirut">\n'
        f'    <path d="{sub}" fill="{DARK_SUB}"/>\n'
        f"  </g>\n"
        f"</svg>\n"
    )


