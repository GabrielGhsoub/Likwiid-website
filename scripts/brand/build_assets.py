import os
import subprocess
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

from monasans import CHOSEN, droplet, font, mark, num, wordmark

SITE = sys.argv[1] if len(sys.argv) > 1 else "/Users/gabriel/Documents/Likwiid/Likwiid-website"
PUB = os.path.join(SITE, "public")
OUT = os.path.dirname(os.path.abspath(__file__))

DARK_BG, DARK_FG, DARK_ACC, DARK_SUB = "#0F1115", "#E8EAF0", "#06B6D4", "#A3ABB8"
LIGHT_FG, LIGHT_ACC = "#1A1A2E", "#0E7490"

wm = wordmark(CHOSEN)
mk = mark(CHOSEN)
W, H = wm["w"], wm["h"]


def run(*args):
    subprocess.run(list(args), check=True)


def text_path(text, size, wght=450, tracking=0.0):
    """Lay out text with Mona Sans advances; returns (svg path at origin baseline, width)."""
    f = font(wght)
    gs = f.getGlyphSet()
    cmap = f.getBestCmap()
    hmtx = f["hmtx"]
    k = size / 1000
    pen = SVGPathPen(gs, ntos=num)
    x = 0.0
    for ch in text:
        g = cmap[ord(ch)]
        gs[g].draw(TransformPen(pen, (k, 0, 0, -k, x, 0)))
        x += hmtx[g][0] * k + tracking
    return pen.getCommands(), x - tracking


