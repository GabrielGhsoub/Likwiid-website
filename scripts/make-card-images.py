"""Card-sized WebP copies of the project screenshots.

Project cards (Home, /software, /work) show a screenshot about 120 px wide for phone screens
and about 350 px wide for web screens, but the originals are 540 to 1440 px wide. This writes
<name>-card.webp next to each card preview (a project's previewImage, else its first image):
720 px wide for web screens, and for phone screens 360 px plus a 240 px <name>-card-sm.webp, since
a 120 px phone card on a 2x screen needs only 240. It also writes src/data/cardImages.ts, which ProjectPreview uses to build a srcset.

Run after adding or replacing a project screenshot:  python3 scripts/make-card-images.py
"""
import os
import re
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..')
OUT_TS = os.path.join(ROOT, 'src', 'data', 'cardImages.ts')
PHONE_WIDTHS = (240, 360)
WEB_WIDTH = 720

# The screenshots cards show: every previewImage, and the first entry of every images list.
with open(os.path.join(ROOT, 'src', 'data', 'projects.ts')) as fh:
    source = fh.read()
previews = set(re.findall(r"previewImage: '([^']+)'", source))
previews |= set(re.findall(r"images: \[\s*'([^']+)'", source))
# Plus screenshots that components reference directly (the Escuela phone on Home, Work and Direct).
for folder, _, files in os.walk(os.path.join(ROOT, 'src', 'components')):
    for name in files:
        with open(os.path.join(folder, name)) as fh:
            previews |= set(re.findall(r"'(/images/projects/[^']+\.webp)'", fh.read()))

entries = []
for url in sorted(previews):
        if not url.endswith('.webp'):
            continue
        path = os.path.join(ROOT, 'public', url.lstrip('/'))
        with Image.open(path) as im:
            im.load()
            targets = PHONE_WIDTHS if im.height > im.width else (WEB_WIDTH,)
            copies = []
            for target in targets:
                if im.width <= target:
                    continue
                suffix = '-card.webp' if target == targets[-1] else '-card-sm.webp'
                card = im.resize((target, round(im.height * target / im.width)), Image.LANCZOS)
                card.save(path[: -len('.webp')] + suffix, 'WEBP', quality=78, method=6)
                copies.append((url[: -len('.webp')] + suffix, target))
            if copies:
                entries.append((url, copies + [(url, im.width)]))

lines = [
    '// Generated by scripts/make-card-images.py. Do not edit by hand.',
    '// Original screenshot -> its srcset candidates as [url, width], smallest first, the original last.',
    'export const CARD_IMAGES: Record<string, ReadonlyArray<readonly [string, number]>> = {',
]
lines += [f"  '{src}': [" + ', '.join(f"['{u}', {w}]" for u, w in copies) + '],' for src, copies in entries]
lines.append('}')
with open(OUT_TS, 'w') as fh:
    fh.write('\n'.join(lines) + '\n')
print(f'{len(entries)} card images written')
